import json
import subprocess
from pathlib import Path

from nougenscript.cli import main
from nougenscript.dynamic_suggestions import render_environment_template, suggest_dynamic_literals


def _repo(path: Path) -> Path:
    path.mkdir()
    subprocess.run(["git", "init", "-q", str(path)], check=True)
    return path


def test_suggests_safe_python_resolution_without_echoing_url(tmp_path):
    root = _repo(tmp_path / "repo")
    source = root / "service.py"
    source.write_text('API_BASE_URL = "https://user:private@example.invalid/v1?key=private"\n', encoding="utf-8")

    items = suggest_dynamic_literals(root)

    assert len(items) == 1
    item = items[0]
    assert (item.path, item.line, item.symbol, item.slot) == ("service.py", 1, "API_BASE_URL", "API_BASE_URL")
    assert item.resolution == 'os.environ["API_BASE_URL"]'
    assert item.required_import == "import os"
    assert "private" not in json.dumps(item.to_dict())


def test_ignores_sensitive_names_and_environment_files(tmp_path):
    root = _repo(tmp_path / "repo")
    (root / "service.py").write_text(
        'API_TOKEN_URL = "https://api.example.invalid"\nAPI_URL = "https://api.example.invalid"\n',
        encoding="utf-8",
    )
    (root / ".env").write_text("API_URL=https://api.example.invalid\n", encoding="utf-8")

    items = suggest_dynamic_literals(root)

    assert [item.symbol for item in items] == ["API_URL"]


def test_language_resolution_is_correct_or_explicitly_unavailable(tmp_path):
    root = _repo(tmp_path / "repo")
    (root / "service.kt").write_text('val API_URL = "https://api.example.invalid"\n', encoding="utf-8")
    (root / "service.rs").write_text('const API_URL: &str = "https://api.example.invalid";\n', encoding="utf-8")
    (root / "service.json").write_text('{"API_URL":"https://api.example.invalid"}\n', encoding="utf-8")

    items = {Path(item.path).suffix: item for item in suggest_dynamic_literals(root)}

    assert items[".kt"].resolution == 'System.getenv("API_URL")'
    assert items[".rs"].resolution == 'std::env::var("API_URL")?'
    assert items[".json"].resolution is None


def test_cli_emits_deterministic_json_suggestions(tmp_path, capsys):
    root = _repo(tmp_path / "repo")
    (root / "service.ts").write_text('const API_URL = "https://api.example.invalid";\n', encoding="utf-8")

    assert main(["suggest-dynamic", str(root), "--json"]) == 0
    output = json.loads(capsys.readouterr().out)

    assert output[0]["resolution"] == "process.env.API_URL"
    assert output[0]["slot"] == "API_URL"


def test_environment_template_is_sorted_and_contains_no_source_values(tmp_path):
    root = _repo(tmp_path / "repo")
    (root / "service.py").write_text(
        'Z_API_URL = "https://private.example.invalid/path"\nA_TIMEOUT = 30\n', encoding="utf-8"
    )

    rendered = render_environment_template(suggest_dynamic_literals(root))

    assert rendered == (
        "# Generated by UDCT. Set each value for this deployment.\n"
        "A_TIMEOUT=\n"
        "Z_API_URL=\n"
    )
    assert "private" not in rendered


def test_scanning_a_checkout_subdirectory_stays_within_that_directory(tmp_path):
    root = _repo(tmp_path / "repo")
    target = root / "component"
    target.mkdir()
    (target / "service.py").write_text('API_URL = "https://component.example.invalid"\n', encoding="utf-8")
    (root / "other.py").write_text('API_URL = "https://outside.example.invalid"\n', encoding="utf-8")

    items = suggest_dynamic_literals(target)

    assert [item.path for item in items] == ["service.py"]
